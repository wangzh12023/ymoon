// Reference vectors for the sync / awareness protocols (y-protocols@1.0.7).
// Usage: node oracle/gen-protocol-vectors.mjs > protocols/vectors_test.mbt
import * as Y from 'yjs'
import * as sync from 'y-protocols/sync'
import * as awp from 'y-protocols/awareness'
import * as encoding from 'lib0/encoding'
const hex = u8 => Buffer.from(u8).toString('hex')
const msg = f => { const e = encoding.createEncoder(); f(e); return hex(encoding.toUint8Array(e)) }

const doc = new Y.Doc(); doc.clientID = 7
doc.getMap('m').set('k', 'v')
const step1 = msg(e => { encoding.writeVarUint(e, 0); sync.writeSyncStep1(e, doc) })
const empty = new Y.Doc(); empty.clientID = 9
const step2 = msg(e => { encoding.writeVarUint(e, 0); sync.writeSyncStep2(e, doc, Y.encodeStateVector(empty)) })
const update = msg(e => { encoding.writeVarUint(e, 0); sync.writeUpdate(e, Y.encodeStateAsUpdate(doc)) })

const aw = new awp.Awareness(doc)
aw.setLocalStateField('user', { name: 'alice', color: '#ff0000' })
aw.setLocalStateField('cursor', { anchor: 3, head: 5 })
const awUpdate = hex(awp.encodeAwarenessUpdate(aw, [7]))
aw.setLocalState(null)
const awRemoved = hex(awp.encodeAwarenessUpdate(aw, [7]))
aw.destroy()

let out = '// Generated by oracle/gen-protocol-vectors.mjs with y-protocols@1.0.7. DO NOT EDIT.\n\n'
out += `///|\nlet ws_sync_step1 : String = "${step1}"\n\n`
out += `///|\nlet ws_sync_step2 : String = "${step2}"\n\n`
out += `///|\nlet ws_sync_update : String = "${update}"\n\n`
out += `///|\nlet awareness_update : String = "${awUpdate}"\n\n`
out += `///|\nlet awareness_removed : String = "${awRemoved}"\n`
process.stdout.write(out)
