// Reference vectors for JSON.stringify / Number#toString, used by lib0 tests.
// Usage: node oracle/gen-json-vectors.mjs > lib0/json_vectors_test.mbt
const buf = new DataView(new ArrayBuffer(8))
const bits = d => { buf.setFloat64(0, d); return '0x' + buf.getBigUint64(0).toString(16).padStart(16, '0') + 'UL' }
const nums = [0, -0, 1, -1, 0.1, 0.2 + 0.1, 1e21, 1e-7, 1.5e-7, 123e-20, 1e300, 5e-324, 1.7976931348623157e308,
  2147483648, 9007199254740993, 0.000001, 123456789.123456789, 1 / 3, 2 / 3, 100, 1e20, 12345678901234567890,
  4.35, 0.5e-6, -1e-7, 3.14159, 255 / 256, 1e16, 1e15 + 0.3, 2 ** 70, -(2 ** -1074), 1.0000000000000002, 299792458]
const BS = String.fromCharCode(92)
const strs = ['', 'plain', 'quote"back' + BS + 'slash', 'ctl\u0000\u0001\u001f\u007f', '\b\f\n\r\t', 'é中😀', '  ', 'a/b',
  String.fromCharCode(0xd800) + 'x', 'y' + String.fromCharCode(0xdfff)]
// MoonBit string literal for an arbitrary JS string (escapes everything risky)
const mbt = s => {
  let out = '"'
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i)
    const isSurrogate = c >= 0xd800 && c <= 0xdfff
    if (isSurrogate && c <= 0xdbff && i + 1 < s.length) {
      const d = s.charCodeAt(i + 1)
      if (d >= 0xdc00 && d <= 0xdfff) {
        out += s[i] + s[i + 1]
        i++
        continue
      }
    }
    if (isSurrogate || c < 0x20 || c === 0x7f || c === 34 || c === 92) {
      out += BS + 'u{' + c.toString(16) + '}'
    } else {
      out += s[i]
    }
  }
  return out + '"'
}
let out = '// Generated by oracle/gen-json-vectors.mjs (Node ' + process.version + '). DO NOT EDIT.\n\n'
out += '///|\nlet number_vectors : ReadOnlyArray[(UInt64, String)] = [\n'
for (const n of nums) out += '  (' + bits(n) + ', ' + mbt(JSON.stringify(n)) + '),\n'
// inputs are UTF-16 code unit arrays: literals cannot hold lone surrogates
const units = s => '[' + Array.from({ length: s.length }, (_, i) => s.charCodeAt(i)).join(', ') + ']'
out += ']\n\n///|\nlet string_vectors : ReadOnlyArray[(ReadOnlyArray[Int], String)] = [\n'
for (const s of strs) out += '  (' + units(s) + ', ' + mbt(JSON.stringify(s)) + '),\n'
out += ']\n'
process.stdout.write(out)
