// Generates lib0 reference vectors used by ymoon's lib0 tests.
// Usage: node conformance/gen-lib0-vectors.mjs > lib0/vectors_test.mbt
import * as encoding from 'lib0/encoding'

const hex = (u8) => Array.from(u8, (b) => b.toString(16).padStart(2, '0')).join('')

const enc = (f) => {
  const e = encoding.createEncoder()
  f(e)
  return hex(encoding.toUint8Array(e))
}

const varUints = [0, 1, 127, 128, 255, 256, 16383, 16384, 2 ** 21 - 1, 2 ** 21, 2 ** 28, 2 ** 31 - 1, 2 ** 32 - 1, 2 ** 32, 2 ** 53 - 1]
const varInts = [0, 1, -1, 63, 64, -63, -64, 8191, 8192, -8192, 2 ** 31 - 1, -(2 ** 31 - 1), -(2 ** 31), 2 ** 40, -(2 ** 52)]
const strings = ['', 'a', 'hello world', 'é', '中文', '😀', 'mixed 中😀é text', '\u0000', 'tab\tnewline\n']
// [label, MoonBit expression, JS value]
const anys = [
  ['undefined', 'Undefined', undefined],
  ['null', 'Null', null],
  ['true', 'Bool(true)', true],
  ['false', 'Bool(false)', false],
  ['int 0', 'Number(0.0)', 0],
  ['negative zero', 'Number(-0.0)', -0],
  ['int 42', 'Number(42.0)', 42],
  ['int -42', 'Number(-42.0)', -42],
  ['int max31', 'Number(2147483647.0)', 2147483647],
  ['int 2^31 (float64)', 'Number(2147483648.0)', 2147483648],
  ['float32 0.5', 'Number(0.5)', 0.5],
  ['float32 1.25e10', 'Number(1.25e10)', 1.25e10],
  ['float64 0.1', 'Number(0.1)', 0.1],
  ['float64 pi', 'Number(3.141592653589793)', 3.141592653589793],
  ['NaN', 'Number(@double.not_a_number)', NaN],
  ['Infinity', 'Number(@double.infinity)', Infinity],
  ['bigint', 'BigInt64(-9007199254740993L)', -9007199254740993n],
  ['string', 'String("yjs ♥ moonbit")', 'yjs ♥ moonbit'],
  ['bytes', 'Bytes(b"\\x00\\x01\\xff")', new Uint8Array([0, 1, 255])],
  ['array', 'Array([Number(1.0), String("two"), Null, Bool(true)])', [1, 'two', null, true]],
  ['object', '@lib0.Any::object([("b", Number(1.0)), ("a", Array([]))])', { b: 1, a: [] }],
  ['object js key order', '@lib0.Any::object([("z", Null), ("10", Null), ("2", Null), ("a", Null), ("01", Null)])', { z: null, 10: null, 2: null, a: null, '01': null }],
  ['nested', '@lib0.Any::object([("list", Array([@lib0.Any::object([("k", String("v"))])]))])', { list: [{ k: 'v' }] }]
]

const mbtString = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/gi, (_, h) => `\\u{${h}}`)

let out = '// Generated by conformance/gen-lib0-vectors.mjs from lib0@0.2.119. DO NOT EDIT.\n'
out += '// Each vector is the exact byte output of the JavaScript reference encoder.\n\n'

out += '///|\nlet var_uint_vectors : ReadOnlyArray[(UInt64, String)] = [\n'
for (const n of varUints) out += `  (${n}UL, "${enc((e) => encoding.writeVarUint(e, n))}"),\n`
out += ']\n\n'

out += '///|\nlet var_int_vectors : ReadOnlyArray[(Int64, String)] = [\n'
for (const n of varInts) out += `  (${n}L, "${enc((e) => encoding.writeVarInt(e, n))}"),\n`
out += ']\n\n'

out += '///|\nlet var_string_vectors : ReadOnlyArray[(String, String)] = [\n'
for (const s of strings) out += `  (${mbtString(s)}, "${enc((e) => encoding.writeVarString(e, s))}"),\n`
out += ']\n\n'

out += '///|\nlet any_vectors : ReadOnlyArray[(String, @lib0.Any, String)] = [\n'
for (const [label, expr, v] of anys) out += `  ("${label}", ${expr}, "${enc((e) => encoding.writeAny(e, v))}"),\n`
out += ']\n'

process.stdout.write(out)
